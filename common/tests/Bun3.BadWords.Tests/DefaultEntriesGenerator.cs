using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using NUnit.Framework;

namespace Bun3.BadWords.Tests
{
    public class DefaultEntriesGenerator
    {
        const string regenerateVariable = "BUN3_BADWORDS_REGEN";

        [Test]
        public void GeneratedDefaultIsUpToDate()
        {
            List<string> entries = ReadDataEntries();
            var filter = new BadWordFilter(entries);
            foreach (string entry in entries)
                if (!entry.StartsWith("!", StringComparison.Ordinal))
                    Assert.That(filter.ContainsBadWord(entry.Trim('|')), Is.True, "Dead block entry: " + entry);
            string runtime = Path.Combine(PackageRoot(), "Runtime");
            var generated = new Dictionary<string, string>
            {
                [Path.Combine(runtime, "BadWordFilter.Default.cs")] = Render(entries),
                [Path.Combine(runtime, "TextNormalizer.Simplified.cs")] = RenderSimplified(ReadSimplifiedPairs()),
            };
            if (Environment.GetEnvironmentVariable(regenerateVariable) == "1")
            {
                foreach (var file in generated) File.WriteAllText(file.Key, file.Value, new UTF8Encoding(false));
                Assert.Pass("Regenerated " + entries.Count + " entries.");
            }
            foreach (var file in generated)
                Assert.That(File.ReadAllText(file.Key).Replace("\r\n", "\n"), Is.EqualTo(file.Value),
                    "Run with " + regenerateVariable + "=1 to regenerate " + Path.GetFileName(file.Key) + ".");
        }

        [Test]
        public void SweepCorpus()
        {
            string corpus = Environment.GetEnvironmentVariable("BUN3_BADWORDS_SWEEP");
            string report = Environment.GetEnvironmentVariable("BUN3_BADWORDS_SWEEP_OUT");
            string misses = Environment.GetEnvironmentVariable("BUN3_BADWORDS_SWEEP_MISSES");
            if (string.IsNullOrEmpty(corpus) || string.IsNullOrEmpty(report)) Assert.Ignore("Set BUN3_BADWORDS_SWEEP and BUN3_BADWORDS_SWEEP_OUT to run.");

            var filter = new BadWordFilter(ReadDataEntries());
            var hits = new Dictionary<string, (int Count, List<string> Samples)>(StringComparer.Ordinal);
            var unblocked = new List<string>();
            foreach (string line in File.ReadLines(corpus, Encoding.UTF8))
            {
                string reason = filter.Explain(line);
                if (reason == null)
                {
                    unblocked.Add(line);
                    continue;
                }
                hits.TryGetValue(reason, out var hit);
                hit.Samples ??= new List<string>();
                if (hit.Samples.Count < 5) hit.Samples.Add(line);
                hits[reason] = (hit.Count + 1, hit.Samples);
            }
            File.WriteAllLines(report, hits.OrderByDescending(pair => pair.Value.Count)
                .Select(pair => pair.Value.Count + "\t" + pair.Key + "\t" + string.Join(" | ", pair.Value.Samples)), Encoding.UTF8);
            if (!string.IsNullOrEmpty(misses)) File.WriteAllLines(misses, unblocked, Encoding.UTF8);
            Assert.Pass(hits.Count + " distinct reasons, " + unblocked.Count + " unblocked lines.");
        }

        internal static List<string> ReadDataEntries() =>
            Directory.GetFiles(Path.Combine(PackageRoot(), "Data~"), "*.txt")
                .Where(path => Path.GetFileName(path) != simplifiedFile)
                .OrderBy(path => Path.GetFileName(path), StringComparer.Ordinal)
                .SelectMany(ReadEntries)
                .ToList();

        static IEnumerable<string> ReadEntries(string path) =>
            File.ReadAllLines(path, Encoding.UTF8)
                .Select(line => line.Trim())
                .Where(line => line.Length > 0 && !line.StartsWith("#", StringComparison.Ordinal));

        internal static string Render(IReadOnlyList<string> entries)
        {
            var builder = new StringBuilder();
            builder.Append("// <auto-generated/>\n");
            builder.Append("// Default dictionary entries generated from the language files in Data~. Regenerate: BUN3_BADWORDS_REGEN=1 dotnet test --filter GeneratedDefaultIsUpToDate\n");
            builder.Append("namespace Bun3.BadWords\n{\n    public sealed partial class BadWordFilter\n    {\n");
            builder.Append("        static string[] CreateDefaultEntries() => new string[]\n        {\n");
            foreach (string entry in entries)
            {
                builder.Append("            \"");
                foreach (char c in entry)
                {
                    if (c >= ' ' && c <= '~' && c != '"' && c != '\\') builder.Append(c);
                    else builder.Append("\\u").Append(((int)c).ToString("X4", CultureInfo.InvariantCulture));
                }
                builder.Append("\",\n");
            }
            builder.Append("        };\n    }\n}\n");
            return builder.ToString();
        }

        const string simplifiedFile = "zh-simplified.txt";

        internal static List<KeyValuePair<char, char>> ReadSimplifiedPairs()
        {
            var pairs = new SortedDictionary<char, char>();
            foreach (string line in ReadEntries(Path.Combine(PackageRoot(), "Data~", simplifiedFile)))
            {
                string[] parts = line.Split('\t');
                Assert.That(parts.Length == 2 && parts[0].Length == 1 && parts[1].Length == 1, Is.True, "Malformed pair: " + line);
                pairs.Add(parts[0][0], parts[1][0]);
            }
            return pairs.ToList();
        }

        internal static string RenderSimplified(IReadOnlyList<KeyValuePair<char, char>> pairs)
        {
            var builder = new StringBuilder();
            builder.Append("// <auto-generated/>\n");
            builder.Append("// Traditional to Simplified Chinese pairs generated from Data~/" + simplifiedFile + ", sorted by the Traditional character. Regenerate: BUN3_BADWORDS_REGEN=1 dotnet test --filter GeneratedDefaultIsUpToDate\n");
            builder.Append("namespace Bun3.BadWords\n{\n    internal static partial class TextNormalizer\n    {\n");
            AppendCharConstant(builder, "traditional", pairs.Select(pair => pair.Key).ToList());
            AppendCharConstant(builder, "simplified", pairs.Select(pair => pair.Value).ToList());
            builder.Append("    }\n}\n");
            return builder.ToString();
        }

        static void AppendCharConstant(StringBuilder builder, string name, List<char> chars)
        {
            builder.Append("        const string ").Append(name).Append(" =");
            if (chars.Count == 0) builder.Append(" \"\"");
            for (int i = 0; i < chars.Count; i += 16)
            {
                builder.Append(i == 0 ? "\n            \"" : " +\n            \"");
                for (int k = i; k < Math.Min(i + 16, chars.Count); k++)
                    builder.Append("\\u").Append(((int)chars[k]).ToString("X4", CultureInfo.InvariantCulture));
                builder.Append('"');
            }
            builder.Append(";\n");
        }

        static string PackageRoot()
        {
            for (var directory = new DirectoryInfo(TestContext.CurrentContext.TestDirectory); directory != null; directory = directory.Parent)
            {
                string candidate = Path.Combine(directory.FullName, "src", "com.bun3.badwords");
                if (Directory.Exists(candidate)) return candidate;
                candidate = Path.Combine(directory.FullName, "common", "src", "com.bun3.badwords");
                if (Directory.Exists(candidate)) return candidate;
            }
            throw new DirectoryNotFoundException("com.bun3.badwords was not found above the test directory.");
        }
    }
}
